"""Emit all 128 relocation-free native variants to stdout (requires clang/llvm-objcopy).

The executor keeps editor hold timing inside the existing 56-byte RTX box:
Fire cancels at 700 ms; +/- repeat at 350 ms, every 120 ms, then 50 ms after 1 s.
"""
import argparse
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile


def tool(name):
    found = shutil.which(name)
    if found:
        return found
    candidates = sorted(Path("C:/Program Files/Microsoft Visual Studio").glob(
        "*/Community/VC/Tools/Llvm/x64/bin/" + name + ".exe"))
    if candidates:
        return str(candidates[-1])
    raise RuntimeError("Supply --" + name + " or add it to PATH")


def symbols_and_relocations(path):
    data = path.read_bytes()
    if data[:7] != b"\x7fELF\x01\x01\x01":
        raise RuntimeError("Expected little-endian ELF32")
    section_offset = struct.unpack_from("<I", data, 32)[0]
    section_size, section_count = struct.unpack_from("<HH", data, 46)
    sections = [struct.unpack_from("<10I", data, section_offset + i * section_size)
                for i in range(section_count)]
    symbols = {}
    for section in sections:
        _, kind, _, _, offset, size, link, _, _, stride = section
        if kind in (4, 9) and size:
            raise RuntimeError("Executor contains unresolved relocations")
        if kind != 2:
            continue
        strings_section = sections[link]
        strings = data[strings_section[4]:strings_section[4] + strings_section[5]]
        for at in range(offset, offset + size, stride):
            name, value, _, _, _, _ = struct.unpack_from("<IIIBBH", data, at)
            end = strings.find(b"\0", name)
            symbols[strings[name:end].decode("ascii")] = value
    return symbols


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang")
    parser.add_argument("--llvm-objcopy")
    args = parser.parse_args()
    clang = args.clang or tool("clang")
    objcopy = args.llvm_objcopy or tool("llvm-objcopy")
    source = Path(__file__).resolve().parents[1] / "src/core/firmware_menu_boot.S"
    variants = [("All", 7, 1), ("Info", 7, 0), ("Voltage", 0, 1), ("Base", 0, 0)]
    variants += [(prefix + str(fields), fields, voltage)
                 for fields in range(1, 7) for prefix, voltage in (("All", 1), ("Info", 0))]
    variants = [(prefix + name, fields, voltage, modules)
                for modules, prefix in enumerate(("", "Puff", "Score", "PuffScore",
                                                   "Rank", "PuffRank", "ScoreRank", "PuffScoreRank"))
                for name, fields, voltage in variants]
    print("// Generated by scripts/generate_menu_executor.py; relocation-free Cortex-M4 Thumb.")
    with tempfile.TemporaryDirectory(prefix="vfs-menu-") as temporary:
        obj = Path(temporary) / "menu.o"
        binary = Path(temporary) / "menu.bin"
        for namespace, fields, voltage, editor in variants:
            subprocess.run([clang, "--target=arm-none-eabi", "-mcpu=cortex-m4", "-mthumb",
                            "-DMENU_INFO=" + str(int(bool(fields))),
                            "-DMENU_INFO_FIELDS=" + str(fields), "-DMENU_VOLTAGE=" + str(voltage),
                            "-DMENU_PUFF_EDITOR=" + str(editor & 1),
                            "-DMENU_SCORE_EDITOR=" + str((editor >> 1) & 1),
                            "-DMENU_RANK_SELECTOR=" + str((editor >> 2) & 1),
                            "-c", str(source), "-o", str(obj)], check=True)
            symbols = symbols_and_relocations(obj)
            subprocess.run([objcopy, "-O", "binary", "--only-section=.text", str(obj), str(binary)], check=True)
            code = binary.read_bytes()
            if symbols["firmware_menu_descriptor"] != len(code):
                raise RuntimeError("Unexpected descriptor/executor size")
            print("namespace " + namespace + " {\nconstexpr uint8_t Executor[] = {")
            for at in range(0, len(code), 16):
                print("    " + ",".join("0x%02x" % b for b in code[at:at + 16]) + ",")
            print("};")
            for public, native in (("Queue", "queue"), ("Main", "main"), ("Voltage", "voltage"),
                                   ("Hud", "hud"), ("Paint", "paint_target"), ("Save", "save"), ("Offsave", "offsave"), ("Start0", "start0"),
                                   ("Start1", "start1"), ("Start2", "start2"), ("Descriptor", "descriptor")):
                print("constexpr size_t %sOffset = %d;" % (public, symbols.get("firmware_menu_" + native, 0) & ~1))
            print("}")


if __name__ == "__main__":
    main()
