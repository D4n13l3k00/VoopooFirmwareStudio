// Each RGB site is MOVS r2/B, r1/G, r0/R; X additionally has four red-mode
// sites with ITT NE between r2 and r1. Those eight bytes must stay together.
// Adjacent Thumb halfwords are checked before accepting a site. Only adjacent
// editable RGB immediate bytes are masked, so edited files retain the guards.
