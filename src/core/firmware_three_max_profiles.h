inline const Profile* Find(FirmwareModel model, FirmwareEdition edition, uint16_t code) {
    if (!code) code = model == FirmwareModel::DragMax ? 0x3021 : 0x3030;
    for (const auto& profile : Profiles)
        if (profile.model == model && profile.edition == edition && profile.code == code) return &profile;
    return nullptr;
}
