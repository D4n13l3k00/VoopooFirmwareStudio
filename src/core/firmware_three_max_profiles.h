// Record-local addresses recovered from each bundled release, including the
// 96x160 controller and the 311C 32-bit settings ABI.
struct Profile {
    FirmwareModel model;
    FirmwareEdition edition;
    uint16_t code;
    uint32_t base, stack, size, scatter, defaults, fill, settings;
    std::array<uint32_t, 20> screens;
    uint32_t animation, delay, mask;
    int width, height;
    bool WideSettings() const { return code == 0x311c; }
    bool ByteCommands() const { return width == 96; }
    uint32_t Gpio() const { return WideSettings() ? 0x40010800 : 0x48000000; }
    uint32_t Spi() const { return WideSettings() ? 0x40013c00 : 0x40003800; }
    uint32_t Flags() const { return WideSettings() ? (edition == FirmwareEdition::Tc ? 0x20000040 : 0x20000034) : edition == FirmwareEdition::Tc ? 0x20000038 : 0x20000030; }
    uint32_t Batteries() const { return WideSettings() ? (edition == FirmwareEdition::Tc ? 0x20000066 : 0x2000004e) : edition == FirmwareEdition::Tc ? 0x2000005e : 0x2000004a; }
    uint32_t Identity() const { return WideSettings() && edition == FirmwareEdition::Factory ? 0x1ffff7f0 : 0x1ffff7ac; }
};
